/// Приводит `\r\n` и одиночные `\r` к `\n`.
///
/// Нужно для вставки текста из буфера обмена: на Windows буфер хранит
/// переносы строк как `\r\n`, а Quill разбивает документ на строки только
/// по `\n`. Оставшийся `\r` не влияет на модель документа, но текстовый
/// движок Flutter (Unicode UAX#14) трактует его как обязательный разрыв
/// строки при рендере — из-за расхождения модели и рендера курсор после
/// вставки смещается на строку вверх, а строка вставки визуально пропадает.
String normalizeLineEndings(String text) {
  return text.replaceAll('\r\n', '\n').replaceAll('\r', '\n');
}
