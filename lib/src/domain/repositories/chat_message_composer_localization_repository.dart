/// Репозиторий для получения локализованных строк для компонентов редактора чата.
///
/// Пользователи пакета должны реализовать этот интерфейс для предоставления
/// локализованных строк в соответствии с их системой локализации.
abstract class ChatMessageComposerLocalizationRepository {
  /// Возвращает локализованный текст для действия съемки фото или видео.
  String get camera;

  /// Возвращает локализованный текст для поля ввода сообщения.
  String get messageText;

  /// Возвращает локализованный текст для действия вставки изображения или видео.
  String get insertImageOrVideo;

  /// Возвращает локализованный текст для действия вставки документа.
  String get insertDocument;

  /// Возвращает локализованный текст для действия прикрепления контакта.
  String get attachContact;

  /// Возвращает локализованный текст для действия создания нового опроса.
  String get createPoll;

  /// Возвращает локализованный текст для действия создания мероприятия.
  String get createEvent;

  /// Возвращает локализованный текст для индикатора режима редактирования сообщения.
  String get editingMessage;

  /// Возвращает локализованный текст для превью цитируемого сообщения без текста (только файлы).
  String get filesLabel;

  /// Возвращает локализованную строку ошибки панели упоминаний.
  /// [error] — текст ошибки от репозитория упоминаний.
  String mentionPanelError(String error);

  /// Возвращает локализованную строку «пользователи не найдены» для панели упоминаний.
  String get mentionPanelNoUsersFound;

  /// Возвращает локализованную строку «эмодзи не найдены» для поиска эмодзи.
  String get emojiNotFound;

  /// Возвращает локализованный текст-подсказку для поля поиска эмодзи.
  String get emojiSearch;
}
