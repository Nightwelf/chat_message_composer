import 'package:cross_file/cross_file.dart';
import 'package:flutter/widgets.dart';

/// Абстрактный интерфейс для выбора файлов.
///
/// Предоставляет методы для выбора файлов и изображений с учетом платформы.
abstract class MessageFilePicker {
  /// Выбирает один или несколько файлов.
  ///
  /// [allowMultiple] - если true, разрешает выбор нескольких файлов.
  /// Возвращает список выбранных файлов или пустой список при отмене/ошибке.
  Future<List<XFile>> pickFiles({bool allowMultiple = false});

  /// Выбирает одно или несколько медиафайлов (фото и видео).
  ///
  /// [allowMultiple] - если true, разрешает выбор нескольких файлов.
  /// Возвращает список выбранных файлов или пустой список при отмене/ошибке.
  Future<List<XFile>> pickMediaFiles({bool allowMultiple = false});

  /// Открывает камеру для съемки фото или видео.
  ///
  /// [context] - контекст для навигации к экрану камеры.
  /// Возвращает список с одним файлом (фото или видео) или пустой список при отмене/ошибке.
  /// На платформах, где камера не поддерживается, возвращает пустой список.
  Future<List<XFile>> pickCameraImage(BuildContext context);
}
